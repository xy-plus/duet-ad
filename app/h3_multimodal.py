"""Pure H3 multimodal contract, prompt compiler, and AutoDL request builder.

This module deliberately performs no provider I/O.  Adapters freeze visual and
audio bytes before entering this boundary; the request builder only encodes
those bytes.  Reference audio is conditioning material, never a target track,
and the audio generated by H3 is the authoritative output.
"""

from __future__ import annotations

import base64
import hashlib
import json
import re
from dataclasses import dataclass, field
from fractions import Fraction
from pathlib import Path
from typing import Literal, Mapping, Sequence

from app.h3 import canonical_json_sha256 as _canonical_sha256


COMPILER_VERSION = "duet.h3-multimodal-context-ir.v1"
MULTIMODAL_WORKFLOW = "minimax_h3_image_audio_to_video_v2_15s"
MULTIMODAL_HD_WORKFLOW = "minimax_h3_image_audio_to_video_v2"

REFERENCE_AUDIO_SEMANTICS = "conditioning_only"
OUTPUT_AUDIO_AUTHORITY = "h3_generated"
MAX_PROMPT_BYTES = 32 * 1024

_IMAGE_MIME_BY_SUFFIX = {
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
}
_AUDIO_MIME_BY_FORMAT = {"mp3": "audio/mpeg", "wav": "audio/wav"}
_AUDIO_KINDS = frozenset({"voice", "sound_effect", "ambience"})
_SUBJECT_ID = re.compile(r"^S([1-9][0-9]*)$")
_LANGUAGE = re.compile(r"^[A-Za-z][A-Za-z0-9_-]{0,31}$")
_RESERVED_PROMPT_SYNTAX = re.compile(
    r"<(?:/?d\b|Picture\s+\d+|Audio\s+\d+|Subject\s+\d+)>|\(S\d+\)",
    re.IGNORECASE,
)

H3Mode = Literal["multimodal", "multimodal_hd"]
AudioKind = Literal["voice", "sound_effect", "ambience"]


class H3MultimodalContractError(RuntimeError):
    """A stable, local validation failure raised before any provider POST."""

    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


def _fail(code: str) -> None:
    raise H3MultimodalContractError(code)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _is_sha256(value: object) -> bool:
    return (
        isinstance(value, str)
        and len(value) == 64
        and all(character in "0123456789abcdef" for character in value)
    )


def _require_optional_sha256(value: object, code: str) -> None:
    if value is not None and not _is_sha256(value):
        _fail(code)


def _require_positive_integer(value: object, code: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        _fail(code)
    return value


def _require_nonblank(value: object, code: str, *, maximum: int = 256) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > maximum:
        _fail(code)
    if any(ord(character) < 32 and character not in "\n\t" for character in value):
        _fail(code)
    return value


def _require_tuple(value: object, code: str) -> tuple:
    if not isinstance(value, tuple):
        _fail(code)
    return value


def _skill_object(
    value: object,
    keys: frozenset[str],
    *,
    code: str = "skill_plan_shape_invalid",
) -> Mapping[str, object]:
    if not isinstance(value, Mapping) or set(value) != keys:
        _fail(code)
    return value


def _skill_list(value: object) -> list[object]:
    if not isinstance(value, list):
        _fail("skill_plan_shape_invalid")
    return value


def _skill_items(value: object, keys: frozenset[str], build) -> tuple:
    return tuple(
        build(_skill_object(item, keys)) for item in _skill_list(value)
    )


@dataclass(frozen=True, slots=True)
class FrozenKeyframe:
    """One already-read image snapshot.  ``order`` is externally 1-based."""

    name: str
    order: int
    data: bytes = field(repr=False)
    sha256: str
    width: int
    height: int
    role: Literal["reference_image"] = "reference_image"

    def __post_init__(self) -> None:
        _require_positive_integer(self.order, "keyframe_order_invalid")
        _require_nonblank(self.name, "keyframe_name_invalid")
        if self.name != Path(self.name).name or "\\" in self.name:
            _fail("keyframe_name_invalid")
        if any(character in self.name for character in "\r\n\t<>"):
            _fail("keyframe_name_invalid")
        if Path(self.name).suffix.lower() not in _IMAGE_MIME_BY_SUFFIX:
            _fail("keyframe_format_invalid")
        if not isinstance(self.data, bytes) or not self.data:
            _fail("keyframe_bytes_invalid")
        if not _is_sha256(self.sha256) or _sha256(self.data) != self.sha256:
            _fail("keyframe_hash_mismatch")
        _require_positive_integer(self.width, "keyframe_dimensions_invalid")
        _require_positive_integer(self.height, "keyframe_dimensions_invalid")
        if self.role != "reference_image":
            _fail("keyframe_role_invalid")


def _keyframe_manifest(frame: FrozenKeyframe) -> dict[str, object]:
    return {
        "name": frame.name,
        "order": frame.order,
        "role": frame.role,
        "sha256": frame.sha256,
        "size_bytes": len(frame.data),
        "width": frame.width,
        "height": frame.height,
    }


@dataclass(frozen=True, slots=True)
class FrozenVisualInput:
    """Generic visual input usable by legacy/canary adapters without a Skill."""

    prompt: str
    prompt_sha256: str
    keyframes: tuple[FrozenKeyframe, ...]
    legacy_plan_sha256: str | None = None
    legacy_meta_sha256: str | None = None
    skill_receipt_sha256: str | None = None

    def __post_init__(self) -> None:
        _require_nonblank(self.prompt, "visual_prompt_invalid", maximum=MAX_PROMPT_BYTES)
        if len(self.prompt.encode("utf-8")) > MAX_PROMPT_BYTES:
            _fail("visual_prompt_invalid")
        if not _is_sha256(self.prompt_sha256) or _sha256(
            self.prompt.encode("utf-8")
        ) != self.prompt_sha256:
            _fail("visual_prompt_hash_mismatch")
        frames = _require_tuple(self.keyframes, "keyframes_not_frozen")
        if not 1 <= len(frames) <= 9:
            _fail("keyframe_count_invalid")
        for expected, frame in enumerate(frames, 1):
            if not isinstance(frame, FrozenKeyframe) or frame.order != expected:
                _fail("keyframe_order_invalid")
            if _sha256(frame.data) != frame.sha256:
                _fail("keyframe_hash_mismatch")
        if len({frame.name for frame in frames}) != len(frames) or len(
            {frame.sha256 for frame in frames}
        ) != len(frames):
            _fail("keyframe_duplicate")
        _require_optional_sha256(self.legacy_plan_sha256, "legacy_plan_hash_invalid")
        _require_optional_sha256(self.legacy_meta_sha256, "legacy_meta_hash_invalid")
        _require_optional_sha256(self.skill_receipt_sha256, "skill_receipt_hash_invalid")


def _visual_manifest(visual: FrozenVisualInput) -> dict[str, object]:
    return {
        "prompt": visual.prompt,
        "prompt_sha256": visual.prompt_sha256,
        "keyframes": [_keyframe_manifest(frame) for frame in visual.keyframes],
        "provenance": {
            "legacy_plan_sha256": visual.legacy_plan_sha256,
            "legacy_meta_sha256": visual.legacy_meta_sha256,
            "skill_receipt_sha256": visual.skill_receipt_sha256,
        },
    }


@dataclass(frozen=True, slots=True)
class FrozenReferenceAudio:
    """One frozen H3 reference-audio artifact, never a target-track promise."""

    order: int
    role: Literal["conditioning_reference"]
    kind: AudioKind
    data: bytes = field(repr=False)
    format: Literal["mp3", "wav"]
    sha256: str
    decoded_sha256: str
    time_base: int
    duration_pts: int

    def __post_init__(self) -> None:
        _require_positive_integer(self.order, "audio_order_invalid")
        if self.role != "conditioning_reference":
            _fail("audio_role_invalid")
        if self.kind not in _AUDIO_KINDS:
            _fail("audio_kind_invalid")
        if self.format not in _AUDIO_MIME_BY_FORMAT:
            _fail("audio_format_invalid")
        if not isinstance(self.data, bytes) or not self.data:
            _fail("audio_bytes_invalid")
        if self.format == "wav" and not (
            len(self.data) >= 12
            and self.data.startswith(b"RIFF")
            and self.data[8:12] == b"WAVE"
        ):
            _fail("audio_format_invalid")
        if self.format == "mp3" and not (
            self.data.startswith(b"ID3")
            or (
                len(self.data) >= 2
                and self.data[0] == 0xFF
                and self.data[1] & 0xE0 == 0xE0
            )
        ):
            _fail("audio_format_invalid")
        if not _is_sha256(self.sha256) or _sha256(self.data) != self.sha256:
            _fail("audio_hash_mismatch")
        if not _is_sha256(self.decoded_sha256):
            _fail("decoded_audio_hash_invalid")
        _require_positive_integer(self.time_base, "audio_time_base_invalid")
        _require_positive_integer(self.duration_pts, "audio_duration_invalid")

def _audio_manifest(audio: FrozenReferenceAudio) -> dict[str, object]:
    return {
        "order": audio.order,
        "role": audio.role,
        "kind": audio.kind,
        "format": audio.format,
        "size_bytes": len(audio.data),
        "sha256": audio.sha256,
        "decoded_sha256": audio.decoded_sha256,
        "probe": {
            "time_base": audio.time_base,
            "duration_pts": audio.duration_pts,
        },
    }


def _require_exact_text(value: object, code: str, *, maximum: int = 2000) -> str:
    text = _require_nonblank(value, code, maximum=maximum)
    if "\n" in text or "\r" in text or "<" in text or ">" in text:
        _fail(code)
    return text


@dataclass(frozen=True, slots=True)
class DialogueLine:
    """One exact spoken line.  It carries order, not a provider PTS promise."""

    order: int
    subject_id: str
    language: str
    text: str

    def __post_init__(self) -> None:
        _require_positive_integer(self.order, "dialogue_order_invalid")
        if not isinstance(self.subject_id, str) or not _SUBJECT_ID.fullmatch(
            self.subject_id
        ):
            _fail("dialogue_subject_invalid")
        if not isinstance(self.language, str) or not _LANGUAGE.fullmatch(self.language):
            _fail("dialogue_language_invalid")
        _require_exact_text(self.text, "dialogue_text_invalid")


@dataclass(frozen=True, slots=True)
class NarrationLine:
    """Ordered off-screen speech, optionally using a frozen voice reference."""

    order: int
    voice_ref: int | None
    language: str
    text: str

    def __post_init__(self) -> None:
        _require_positive_integer(self.order, "narration_order_invalid")
        if self.voice_ref is not None:
            _require_positive_integer(self.voice_ref, "narration_voice_ref_invalid")
        if not isinstance(self.language, str) or not _LANGUAGE.fullmatch(self.language):
            _fail("narration_language_invalid")
        _require_exact_text(self.text, "narration_text_invalid")


@dataclass(frozen=True, slots=True)
class SubjectBinding:
    """Skill-compatible speaker/face/voice binding using 1-based references."""

    subject_id: str
    picture_refs: tuple[int, ...]
    voice_ref: int | None

    def __post_init__(self) -> None:
        match = _SUBJECT_ID.fullmatch(self.subject_id) if isinstance(
            self.subject_id, str
        ) else None
        if match is None:
            _fail("subject_id_invalid")
        pictures = _require_tuple(self.picture_refs, "subject_picture_refs_invalid")
        if not pictures or any(
            isinstance(value, bool) or not isinstance(value, int) or value <= 0
            for value in pictures
        ):
            _fail("subject_picture_refs_invalid")
        if tuple(sorted(set(pictures))) != pictures:
            _fail("subject_picture_refs_invalid")
        if self.voice_ref is not None:
            _require_positive_integer(self.voice_ref, "subject_voice_ref_invalid")


@dataclass(frozen=True, slots=True)
class SoundReference:
    """An exact semantic intent for one ambience or sound-effect reference."""

    audio_index: int
    description: str

    def __post_init__(self) -> None:
        _require_positive_integer(self.audio_index, "sound_reference_invalid")
        _require_exact_text(self.description, "sound_reference_invalid")


@dataclass(frozen=True, slots=True)
class SoundDesign:
    """Strict backend DTO for the Skill's still-evolving sound_design object."""

    narration: tuple[NarrationLine, ...] = ()
    ambience_refs: tuple[SoundReference, ...] = ()
    effects: tuple[SoundReference, ...] = ()

    def __post_init__(self) -> None:
        _require_tuple(self.narration, "sound_design_not_frozen")
        _require_tuple(self.ambience_refs, "sound_design_not_frozen")
        _require_tuple(self.effects, "sound_design_not_frozen")
        if not all(isinstance(item, NarrationLine) for item in self.narration):
            _fail("sound_design_invalid")
        if not all(
            isinstance(item, SoundReference)
            for item in self.ambience_refs + self.effects
        ):
            _fail("sound_design_invalid")


